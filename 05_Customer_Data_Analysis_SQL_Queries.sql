-- Question 6: Which age category sold more products?
-- Purpose: To calculate the total products sold by each age group.

SELECT
    CASE
        WHEN age BETWEEN 18 AND 29 THEN '18-29'
        WHEN age BETWEEN 30 AND 39 THEN '30-39'
        WHEN age BETWEEN 40 AND 49 THEN '40-49'
        WHEN age BETWEEN 50 AND 59 THEN '50-59'
        WHEN age BETWEEN 60 AND 69 THEN '60-69'
    END AS age_group,

    SUM(quantity) AS total_products

FROM customer

WHERE age BETWEEN 18 AND 69

GROUP BY age_group

ORDER BY
    CASE age_group
        WHEN '18-29' THEN 1
        WHEN '30-39' THEN 2
        WHEN '40-49' THEN 3
        WHEN '50-59' THEN 4
        WHEN '60-69' THEN 5
    END; 

