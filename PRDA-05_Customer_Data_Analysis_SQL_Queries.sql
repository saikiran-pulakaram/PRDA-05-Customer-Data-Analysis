-- Purpose: To display all databases available on the MySQL server.
-- Note: information_schema is a MySQL system database.
-- project_customer_segmentation is the database used for this project.
SHOW DATABASES;

-- Purpose: To select the project_customer_segmentation database
-- so that the following queries are executed within this database.
USE project_customer_segmentation;


-- Purpose: To display all tables available inside the selected database.
SHOW TABLES;

-- Purpose: To understand the structure of the customer table,
-- including its columns, data types, NULL settings, and keys.
DESCRIBE customer;

-- Purpose: To find the total number of records available in the customer table.
SELECT COUNT(*) AS total_records
FROM customer;

-- Purpose: To count the total number of columns in the customer table.

SELECT COUNT(*) AS total_columns
FROM INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_SCHEMA = 'project_customer_segmentation'
  AND TABLE_NAME = 'customer';
  
  -- Purpose: To count the NULL values in the gender column.

SELECT COUNT(*) AS null_gender
FROM customer
WHERE gender IS NULL;


-- Purpose: To count the NULL values present in each column of the customer table.
SELECT
    SUM(invoice_no IS NULL) AS null_invoice_no,
    SUM(customer_id IS NULL) AS null_customer_id,
    SUM(gender IS NULL) AS null_gender,
    SUM(age IS NULL) AS null_age,
    SUM(category IS NULL) AS null_category,
    SUM(quantity IS NULL) AS null_quantity,
    SUM(price IS NULL) AS null_price,
    SUM(payment_method IS NULL) AS null_payment_method,
    SUM(invoice_date IS NULL) AS null_invoice_date,
    SUM(shopping_mall IS NULL) AS null_shopping_mall
FROM customer; 

-- Purpose: To identify invoice numbers that appear more than once.

SELECT
    invoice_no,
    COUNT(*) AS occurrence_count
FROM customer
GROUP BY invoice_no
HAVING COUNT(*) > 1;

## PRDA – 04 Customer Data Analysis  

-- 1. How is shopping distributed by gender?
-- Purpose: To identify all distinct gender values in the customer table.

SELECT DISTINCT gender
FROM customer;

-- Purpose: To count the transaction records for each gender.

SELECT
    gender,
    COUNT(*) AS total_records
FROM customer
GROUP BY gender;

-- Question 2: Which gender did we sell more products to?

-- Purpose: To calculate the total quantity of products sold to each gender.

SELECT
    gender,
    SUM(quantity) AS total_products
FROM customer
GROUP BY gender;


--  Question 3: Which gender generated more revenue?
-- Purpose: To calculate total revenue generated by each gender.

SELECT
    gender,
    SUM(quantity * price) AS total_revenue
FROM customer
GROUP BY gender;

-- Question 4: Distribution of purchase categories relative to other columns?

